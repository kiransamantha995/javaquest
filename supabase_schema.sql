  for update using (auth.uid() = user_id);

create policy "Badges delete policy" on public.earned_badges
  for delete using (auth.uid() = user_id);

-- 4. Automatic profile initialization trigger
create or replace function public.handle_new_user()
returns trigger as $$
begin
  insert into public.profiles (id, username, difficulty, avatar_skin)
  values (
    new.id,
    coalesce(new.raw_user_meta_data->>'username', 'JavaLearner'),
    coalesce(new.raw_user_meta_data->>'difficulty', 'beginner'),
    coalesce((new.raw_user_meta_data->>'avatar_skin')::int, 0)
  )
  on conflict (id) do nothing;

  insert into public.progress (user_id)
  values (new.id)
  on conflict (user_id) do nothing;

  return new;
end;
$$ language plpgsql security definer;

create or replace trigger on_auth_user_created
  after insert on auth.users
  for each row execute procedure public.handle_new_user();
