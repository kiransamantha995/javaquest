-- Run this in your Supabase SQL editor if setting up a fresh project.

-- 1. Profiles Table
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username text default 'JavaLearner',
  difficulty text default 'beginner',
  avatar_skin integer default 0,
  avatar_hair integer default 0,
  avatar_hair_color integer default 0,
  avatar_outfit integer default 0,
  avatar_accessory integer default 0,
  xp integer default 0,
  level integer default 1,
  streak integer default 0,
  last_visit text,
  hearts integer default 3,
  heart_refill_at timestamp with time zone,
  updated_at timestamp with time zone default timezone('utc'::text, now())
);

alter table public.profiles enable row level security;

create policy "Profiles select policy" on public.profiles
  for select using (auth.uid() = id);

create policy "Profiles insert policy" on public.profiles
  for insert with check (auth.uid() = id);

create policy "Profiles update policy" on public.profiles
  for update using (auth.uid() = id);

create policy "Profiles delete policy" on public.profiles
  for delete using (auth.uid() = id);

-- 2. Progress Table
create table if not exists public.progress (
  user_id uuid primary key references auth.users(id) on delete cascade,
  completed_lessons jsonb default '[]'::jsonb,
  completed_challenges jsonb default '[]'::jsonb,
  completed_modules jsonb default '[]'::jsonb,
  completed_coding jsonb default '[]'::jsonb,
  coding_attempts jsonb default '{}'::jsonb,
  capstone_projects jsonb default '{}'::jsonb,
  updated_at timestamp with time zone default timezone('utc'::text, now())
);

alter table public.progress enable row level security;

create policy "Progress select policy" on public.progress
  for select using (auth.uid() = user_id);

create policy "Progress insert policy" on public.progress
  for insert with check (auth.uid() = user_id);

create policy "Progress update policy" on public.progress
  for update using (auth.uid() = user_id);

create policy "Progress delete policy" on public.progress
  for delete using (auth.uid() = user_id);

-- 3. Earned Badges Table
create table if not exists public.earned_badges (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users(id) on delete cascade not null,
  badge_id text not null,
  earned_at timestamp with time zone default timezone('utc'::text, now()),
  constraint earned_badges_user_badge_unique unique (user_id, badge_id)
);

alter table public.earned_badges enable row level security;

create policy "Badges select policy" on public.earned_badges
  for select using (auth.uid() = user_id);

create policy "Badges insert policy" on public.earned_badges
